import type { ISODate } from '../domain/dates'
import type { HabitGoal, HabitKind, TimeOfDay } from '../domain/habits'

export type { ISODate }

/** Fields every synced record has. `updatedAt`/`deletedAt` are ISO timestamps (instants, not days). */
export interface SyncFields {
  id: string
  updatedAt: string
  /** Soft delete: deleted records are kept (and synced) so the deletion reaches other devices. */
  deletedAt?: string
}

export interface Habit extends SyncFields {
  name: string
  emoji?: string
  color?: string
  startDate: ISODate
  endDate?: ISODate
  /** Missing on habits created before types existed → 'fixed' (every day). */
  kind?: HabitKind
  /** Fixed and scheduled habits: moment of the day to group them in "Hoy". */
  timeOfDay?: TimeOfDay
  /** Scheduled: a single date… */
  onDate?: ISODate
  /** …or some weekdays (0 = Sunday). */
  weekdays?: number[]
  /** Progress habits. */
  goal?: HabitGoal
  order: number
  createdAt: string
}

export interface HabitLog extends SyncFields {
  /** `${habitId}|${date}` — deterministic so two devices toggling the same cell hit the same record. */
  habitId: string
  date: ISODate
  done: boolean
  /** Progress habits with an amount goal: how much was done that day. */
  amount?: number
}

export interface DayMood extends SyncFields {
  /** id === date */
  date: ISODate
  mood?: number
  motivation?: number
}

/**
 * - `items`: an ordered list of things to finish (rooms, lessons, chapters). Pace = items per day.
 * - `amount`: a total quantity (hours, pages, exercises) logged per day. Pace = units per day.
 */
export type PlanKind = 'items' | 'amount'

export interface Plan extends SyncFields {
  name: string
  /** Missing on plans created before amount plans existed → 'items'. */
  kind?: PlanKind
  /** Display unit: "rooms", "horas", "páginas"… Optional for item plans. */
  unit?: string
  /** Amount plans only: total to reach. */
  target?: number
  startDate: ISODate
  deadline: ISODate
  pace: number
  restWeekdays: number[]
  blockedDates: ISODate[]
  linkedHabitId?: string
  /** Plan original: itemId → fecha. Fixed; only regenerated by "Replanificar desde hoy". */
  baseline: Record<string, ISODate>
  createdAt: string
}

export interface PlanItem extends SyncFields {
  planId: string
  title: string
  section?: string
  notes?: string
  order: number
  done: boolean
  doneDate?: ISODate
  /** Done before the plan started (e.g. rooms 1–31 when you start at 32): counts in the total, never scheduled. */
  prior?: boolean
}

/** Amount plans: how much was done on a day (id === `${planId}|${date}`, one record per plan and day). */
export interface PlanLog extends SyncFields {
  planId: string
  date: ISODate
  amount: number
}

/** One weigh-in per day (id === date). */
export interface BodyWeight extends SyncFields {
  date: ISODate
  kg: number
}

export type Meal = 'desayuno' | 'almuerzo' | 'merienda' | 'cena' | 'snack'

/** One line of a meal typed as text ("200 g arroz"), with what it was computed as. */
export interface FoodItem {
  text: string
  /** Built-in food id or custom food id. Missing when the kcal were typed by hand. */
  foodId?: string
  /** Grams (ml for liquids), when known. */
  grams?: number
  kcal: number
}

export interface FoodEntry extends SyncFields {
  date: ISODate
  kcal: number
  label?: string
  meal?: Meal
  /** Breakdown when the meal was typed as text. */
  items?: FoodItem[]
}

/** "Mis alimentos": foods the user taught the app. Either per 100 g or per unit. */
export interface CustomFood extends SyncFields {
  name: string
  /** kcal per 100 g. */
  kcal100?: number
  /** kcal of one unit. */
  kcalPerUnit?: number
  /** Grams of one unit (optional). */
  unitGrams?: number
}

/** Last projection computed on a device (id === planId). The server reads it for "Hoy toca: Room 12". */
export interface PlanProjection extends SyncFields {
  planId: string
  computedOn: ISODate
  dates: Record<string, ISODate>
}

export interface Milestone extends SyncFields {
  planId: string
  title: string
  from: ISODate
  to: ISODate
  description?: string
  done: boolean
}

export interface Task extends SyncFields {
  date: ISODate
  /** 'HH:MM' */
  time?: string
  title: string
  done: boolean
  order: number
}

export interface Settings extends SyncFields {
  /** id === 'prefs' */
  weekStartsMonday: boolean
  reminderEnabled: boolean
  /** 'HH:MM' local time of the morning reminder. */
  reminderTime: string
  timeZone: string
  /** Sunday-night push with the week's summary. Missing = on if the morning reminder is on. */
  weeklySummary?: boolean
  /** Optional weight & calorie tracking ("Salud" tab). */
  healthEnabled?: boolean
  /** kcal per day. */
  calorieTarget?: number
  /** kg. */
  weightGoal?: number
}

export interface PushSubscriptionRecord extends SyncFields {
  endpoint: string
  keys: { p256dh: string; auth: string }
  userAgent?: string
}

export interface CollectionMap {
  habits: Habit
  habitLogs: HabitLog
  dayMoods: DayMood
  plans: Plan
  planItems: PlanItem
  planLogs: PlanLog
  milestones: Milestone
  projections: PlanProjection
  tasks: Task
  bodyWeights: BodyWeight
  foodEntries: FoodEntry
  customFoods: CustomFood
  settings: Settings
  pushSubscriptions: PushSubscriptionRecord
}

export type CollectionName = keyof CollectionMap

