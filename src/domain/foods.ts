/**
 * Built-in dictionary of foods common in Argentina, with approximate energy values.
 *
 * - `kcal`: kcal per 100 g, or per 100 ml when `liquid` is set.
 * - `units`: grams (ml for liquids) of ONE household unit, only where it makes sense
 *   (a "unidad" of huevo, a "feta" of jamón, a "plato" of fideos…). Volume units the food
 *   doesn't define (taza, vaso, cda, cdta) fall back to generic sizes in `foodLog.ts`.
 * - Values are approximations from standard tables (USDA FoodData Central, Argentine tables
 *   and typical labels). When cooking changes the value a lot the name says how it's counted
 *   (arroz → cocido, fideos → cocidos), defaulting to the way people usually log it.
 *
 * Pure data: no logic here. `foods.test.ts` checks ids and names/aliases don't collide.
 */

export type HouseholdUnit = 'unidad' | 'taza' | 'vaso' | 'cda' | 'cdta' | 'feta' | 'rebanada' | 'porcion' | 'plato'

export interface FoodDef {
  id: string
  name: string
  aliases: string[]
  /** kcal per 100 g (per 100 ml when `liquid`). */
  kcal: number
  liquid?: boolean
  /** g (ml when `liquid`) per household unit. */
  units: Partial<Record<HouseholdUnit, number>>
}

type U = FoodDef['units']

/** Solid food. `aliases` is a "|"-separated list to keep the table compact. */
const s = (id: string, name: string, kcal: number, aliases = '', units: U = {}): FoodDef => ({
  id,
  name,
  aliases: aliases ? aliases.split('|') : [],
  kcal,
  units,
})

/** Liquid: kcal per 100 ml and units in ml. */
const l = (id: string, name: string, kcal: number, aliases = '', units: U = {}): FoodDef => ({
  ...s(id, name, kcal, aliases, units),
  liquid: true,
})

